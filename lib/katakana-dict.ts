/**
 * Katakana loanword → source-word dictionary.
 *
 * Most katakana in modern Japanese are 外来語 (gairaigo) borrowed from English.
 * Showing the source word above the katakana turns an opaque string of symbols
 * into something a learner can decode instantly ("ゲレンデ" → "Gelände").
 *
 * `src` marks the origin language when it is NOT English — that detail matters,
 * because guessing an English word for パン or アルバイト leads learners astray.
 */

export type LoanEntry = {
  /** Source word shown above the katakana. Keep it short — it sets the box width. */
  en: string
  /** Origin language when not English (de/fr/pt/nl/it/es/ru). */
  src?: string
}

