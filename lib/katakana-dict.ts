/**
 * Katakana strings that are NOT loanwords: onomatopoeia, native words written in
 * katakana for emphasis, and script names. Glossing these with English would be
 * actively wrong, so they short-circuit both the dictionary and the LLM lookup.
 */
export const NON_LOANWORDS = new Set([
  // Script / language names
  "カタカナ", "ヒラガナ", "ローマジ", "ニホン", "ニホンゴ", "ニッポン",
  // Onomatopoeia & mimetic words
  "ドキドキ", "ワクワク", "ペコペコ", "ニコニコ", "キラキラ", "ゴロゴロ",
  "バタバタ", "ハラハラ", "イライラ", "ソワソワ", "フワフワ", "サラサラ",
  "ベタベタ", "ザラザラ", "ツルツル", "モチモチ", "サクサク", "パリパリ",
  "ジュージュー", "グツグツ", "ゴクゴク", "パクパク", "モグモグ",
  "スースー", "ヒヤヒヤ", "ドンドン", "バンバン", "ガンガン", "シーン",
  // Native words commonly written in katakana
  "コツ", "ウソ", "ダメ", "スゴイ", "ヤバイ", "オレ", "ボク", "アナタ",
  "コブ", "ヒザ", "コシ", "アシ", "テ", "メ", "クチ", "アタマ", "カラダ",
  "マンガ", "スミマセン", "アリガトウ", "コンニチハ", "ゴミ", "サカナ",
  "ヤマ", "ユキ", "ミズ", "クルマ", "イヌ", "ネコ", "トリ", "ハナ",
])

/** Terms whose dictionary value is an empty string are structural guards, not glosses. */
export function lookupLoanword(term: string): LoanEntry | null {
  if (NON_LOANWORDS.has(term)) return null
  const entry = KATAKANA_DICT[term]
  if (!entry || !entry.en) return null
  return entry
}

/** Longest dictionary key, used to bound the greedy match window. */
export const MAX_TERM_LENGTH = Object.keys(KATAKANA_DICT).reduce(
  (max, k) => Math.max(max, k.length),
  0
)
